$destDir = Join-Path $PSScriptRoot "public\images"
if (-not (Test-Path $destDir)) {
    New-Item -ItemType Directory -Path $destDir -Force | Out-Null
}

$headers = @{
    "User-Agent" = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
}

foreach ($img in $images) {
    $outFile = Join-Path $destDir $img.file
    
    # Skip if file already downloaded successfully and is not tiny
    if (Test-Path $outFile) {
        $size = (Get-Item $outFile).Length
        if ($size -gt 1000) {
            Write-Host "Skipping (Already Exists): $($img.file)"
            continue
        }
    }
    
    Write-Host "Downloading: $($img.file)..."
    try {
        Invoke-WebRequest -Uri $img.url -OutFile $outFile -Headers $headers -TimeoutSec 15
        Write-Host "Saved: $($img.file)"
    } catch {
        Write-Warning "Failed to download $($img.file): $_"
    }
    Start-Sleep -Milliseconds 150
}
Write-Host "All assets downloaded successfully!"
